"""The lockfiles, checked against the intent they were compiled from.

`requirements.in` says what this service needs and why. `requirements.txt`
is compiled from it with every transitive dependency pinned and hashed, and
that second file is what Docker, CI and `make install` actually read.

Two files can drift. Somebody edits the `.in` and forgets `make lock`, and
the thing that ships is whatever was locked last month. These tests are the
cheapest way to notice, and they run in the same suite as everything else.

What a hash buys, since it is easy to wave at: without one, `pip install
fastapi==0.143.0` trusts whatever the index hands back under that name
today. With one, a replaced or tampered artefact fails the install instead
of reaching production.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]

# name==version at the start of a line, which is how both pip-compile and a
# hand-written pin spell it.
PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\\;]+)")


def declared(path: Path) -> dict[str, str]:
    """The pins a human wrote, ignoring comments and options."""
    found = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "-")):
            continue
        # Extras are part of the install, not of the name: uvicorn[standard]
        # and uvicorn are the same project to the resolver, and --strip-extras
        # means the lockfile only ever spells the bare name.
        if match := PIN.match(re.sub(r"\[[^\]]*\]", "", line)):
            found[match.group(1).lower().replace("_", "-")] = match.group(2)
    return found


def locked(path: Path) -> dict[str, str]:
    """Everything the lockfile pins, direct and transitive alike."""
    return {
        match.group(1).lower().replace("_", "-"): match.group(2)
        for line in path.read_text().splitlines()
        if (match := PIN.match(line.strip()))
    }


def hashes(path: Path) -> dict[str, int]:
    """How many hashes each pinned package carries."""
    counts: dict[str, int] = {}
    current = None
    for line in path.read_text().splitlines():
        if match := PIN.match(line.strip()):
            current = match.group(1).lower().replace("_", "-")
            counts.setdefault(current, 0)
        elif current and "--hash=sha256:" in line:
            counts[current] += 1
    return counts


PAIRS = [
    ("requirements.in", "requirements.txt"),
    ("requirements-dev.in", "requirements-dev.txt"),
]


@pytest.mark.parametrize(("intent", "lockfile"), PAIRS)
def test_the_lockfile_exists_and_was_generated_rather_than_written(intent, lockfile):
    text = (ROOT / lockfile).read_text()
    assert "autogenerated by pip-compile" in text, (
        f"{lockfile} looks hand-edited. Run `make lock` and commit the result."
    )
    assert "--generate-hashes" in text


@pytest.mark.parametrize(("intent", "lockfile"), PAIRS)
def test_every_package_in_the_lockfile_is_pinned_and_hashed(intent, lockfile):
    """--require-hashes refuses the whole install if one line lacks a hash,
    so a gap here is a build that fails rather than one that ships."""
    counted = hashes(ROOT / lockfile)
    assert counted, f"{lockfile} pins nothing"
    unhashed = [name for name, count in counted.items() if count == 0]
    assert not unhashed, f"{lockfile} pins {unhashed} with no hash"


@pytest.mark.parametrize(("intent", "lockfile"), PAIRS)
def test_the_lockfile_agrees_with_what_was_asked_for(intent, lockfile):
    """The drift check.

    Every direct dependency is pinned exactly in the `.in`, so the lockfile
    must carry that same version. If this fails, someone changed the `.in`
    and did not run `make lock` - and the thing that ships is the old pin.
    """
    wanted = declared(ROOT / intent)
    got = locked(ROOT / lockfile)
    assert wanted, f"{intent} declares nothing"
    for name, version in wanted.items():
        assert name in got, f"{name} is in {intent} but not in {lockfile}"
        assert got[name] == version, (
            f"{intent} asks for {name}=={version}, {lockfile} has {got[name]}. "
            "Run `make lock`."
        )


def test_the_two_lockfiles_do_not_disagree_about_a_shared_package():
    """CI installs both at once. Two pins for one package fails the install.

    `requirements-dev.in` constrains itself against the runtime lockfile for
    this reason; this is the test that says so out loud.
    """
    runtime = locked(ROOT / "requirements.txt")
    dev = locked(ROOT / "requirements-dev.txt")
    clashes = {
        name: (runtime[name], dev[name])
        for name in set(runtime) & set(dev)
        if runtime[name] != dev[name]
    }
    assert not clashes, f"the two lockfiles disagree: {clashes}"


def test_nothing_the_code_imports_is_missing_from_the_runtime_lockfile():
    """The failure this catches actually happened.

    `httpx` was imported in four modules and declared in neither file - it
    was arriving as somebody else's transitive dependency, so a pin nobody
    here controlled decided our HTTP behaviour. It would have vanished the
    day that package dropped it.
    """
    third_party = {"httpx", "fastapi", "uvicorn", "websockets", "dotenv"}
    imported = set()
    for path in (ROOT / "src").rglob("*.py"):
        for line in path.read_text().splitlines():
            if match := re.match(r"\s*(?:import|from)\s+([a-z_][a-z_0-9]*)", line):
                if match.group(1) in third_party:
                    imported.add(match.group(1))

    # The import name and the distribution name differ for exactly one of
    # these, which is its own small trap.
    distribution = {"dotenv": "python-dotenv"}
    pinned = locked(ROOT / "requirements.txt")
    for name in imported:
        assert distribution.get(name, name) in pinned, (
            f"src imports {name} but requirements.in never asks for it"
        )
